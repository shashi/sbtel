#!/usr/bin/env node
// Writes big-a.sbtel (~670 blocks) and big-b.sbtel (the same spec after renames, moves, removals, additions,
// sketch and port edits). Deterministic. Run from anywhere:
//   node conformance/diff/gen-big.mjs
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
let s = 7; const rnd = () => (s = (s * 1664525 + 1013904223) >>> 0) / 4294967296;
const pick = a => a[Math.floor(rnd() * a.length)];
const kinds = ['Req', 'Evt', 'Row', 'Cmd', 'Ack'];
const verbs = ['Keeps', 'Sends', 'Reads', 'Checks', 'Draws', 'Stores', 'Routes', 'Counts'];
const objs = ['the latest state per key', 'every event to subscribers', 'rows from disk', 'input before it reaches storage', 'the visible part of the list', 'failed deliveries for a human', 'requests to their handlers', 'how often each thing happens'];

// Tree: 12 areas x 5 modules x 10 parts.
const tree = [];
for (let a = 0; a < 12; a++) {
  const area = { name: 'Area' + a, kids: [] };
  for (let m = 0; m < 5; m++) {
    const mod = { name: `Area${a}.Mod${m}`, kids: [] };
    for (let p = 0; p < 10; p++) mod.kids.push({ name: `Area${a}.Mod${m}.Part${p}`, kids: [] });
    area.kids.push(mod);
  }
  tree.push(area);
}
const all = []; const walk = n => { all.push(n); n.kids.forEach(walk); }; tree.forEach(walk);
all.forEach(n => {
  n.sketch = pick(verbs) + ' ' + pick(objs) + '.';
  n.ports = []; if (rnd() < .5) n.ports.push(['in', 'in', pick(kinds)]); if (rnd() < .4) n.ports.push(['out', 'out', pick(kinds)]);
  n.adj = rnd() < .3;
});

function emit(roots, refinesAck) {
  const blk = (n, ind) => {
    let t = `${ind}(block ${n.name}`;
    n.ports.forEach(p => { t += `\n${ind}  (${p[1] === 'in' ? 'takes' : 'gives'} ${p[2]} :as ${p[0]})`; });
    t += `\n${ind}  (sketch "${n.sketch}")`;
    if (n.kids.length) {
      // Two levels: the first half and the second half; pairs flagged adj are grouped.
      const half = Math.ceil(n.kids.length / 2);
      [n.kids.slice(0, half), n.kids.slice(half)].filter(l => l.length).forEach(L => {
        t += `\n${ind}  (level`;
        for (let i = 0; i < L.length; i++) {
          if (L[i].adj && i + 1 < L.length) { t += `\n${ind}    (adjacent\n${blk(L[i], ind + '      ')}\n${blk(L[i + 1], ind + '      ')})`; i++; }
          else t += '\n' + blk(L[i], ind + '    ');
        }
        t += ')';
      });
    }
    return t + ')';
  };
  return '; Generated by gen-big.mjs: a large spec for diff performance.\n(block Big\n' +
    kinds.map(k => `  (shape ${k}${k === 'Ack' && refinesAck ? ' (refines Evt)' : ''} (sketch "A ${k.toLowerCase()}."))`).join('\n') + '\n' +
    '  (level\n' + roots.map(r => blk(r, '    ')).join('\n') + '))\n';
}
writeFileSync(join(here, 'big-a.sbtel'), emit(tree, false));

// Side b.
const clone = n => ({ ...n, ports: n.ports.map(p => [...p]), kids: n.kids.map(clone) });
const t2 = tree.map(clone), all2 = []; const walk2 = n => { all2.push(n); n.kids.forEach(walk2); }; t2.forEach(walk2);
const parts = all2.filter(n => !n.kids.length), mods = all2.filter(n => n.name.split('.').length === 2);
for (let i = 0; i < 20; i++) { const n = parts[(i * 29) % parts.length]; n.name = n.name.replace('Part', 'Piece'); }
for (let i = 0; i < 30; i++) { const n = parts[(i * 17 + 3) % parts.length]; n.sketch = n.sketch.replace('.', ', and logs it.'); }
for (let i = 0; i < 12; i++) { const n = parts[(i * 41 + 5) % parts.length]; if (n.ports.length) n.ports.pop(); else n.ports.push(['extra', 'in', 'Cmd']); }
// Moves: parts to another module; a whole module to another area.
for (let i = 0; i < 15; i++) { const from = mods[(i * 7) % mods.length], to = mods[(i * 7 + 13) % mods.length]; if (from.kids.length > 2) to.kids.push(from.kids.splice(1, 1)[0]); }
t2[3].kids.push(t2[1].kids.splice(2, 1)[0]);
// Removals: a module with its parts, and single parts. Additions.
t2[5].kids.splice(4, 1);
for (let i = 0; i < 8; i++) { const m = mods[(i * 11 + 2) % mods.length]; if (m.kids.length > 3) m.kids.splice(m.kids.length - 1, 1); }
for (let i = 0; i < 10; i++) mods[(i * 5 + 1) % mods.length].kids.push({ name: `New${i}`, sketch: 'Added in this revision.', ports: [], kids: [], adj: false });
writeFileSync(join(here, 'big-b.sbtel'), emit(t2, false));
console.log('wrote big-a.sbtel and big-b.sbtel');
